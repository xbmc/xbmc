// An RPU with just its header, which refers back to data mapping 0. It was made for the test, as
// none of the streams at hand has one.
const std::vector<uint8_t> MAPPING_0_RPU = {
    0x19, 0x08, 0x09, 0x08, 0x40, 0x61, 0x36, 0x50, 0x98, 0xC9, 0xB5, 0xC3,
    0xE6, 0x80,
};
// clang-format on

// The RPU of a NAL unit, as FFmpeg's decoder takes it
std::vector<uint8_t> Rpu(const std::vector<uint8_t>& nal)
{
  std::vector<uint8_t> rpu{HevcRpuToNal(nal.data() + 2, nal.size() - 2)};
  rpu.erase(rpu.begin(), rpu.begin() + 2);
  return rpu;
}

// Sets the CRC32 before an RPU's terminator to the one of what precedes it, after the prefix
std::vector<uint8_t> WithCrc(std::vector<uint8_t> rpu)
{
  const size_t end{rpu.size() - 5};
  Crc32 crc;
  crc.Compute(reinterpret_cast<const char*>(rpu.data() + 1), end - 1);
  for (size_t i = 0; i < 4; ++i)
    rpu[end + i] = static_cast<uint8_t>(static_cast<uint32_t>(crc) >> (24 - 8 * i));
  return rpu;
}
