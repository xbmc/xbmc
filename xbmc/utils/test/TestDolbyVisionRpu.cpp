TEST(TestDolbyVisionRpu, AnRpuWithoutAResidualHasNoEnhancementLayer)
{
  CRpuReader reader;
  EXPECT_EQ(EnhancementLayer::NONE, reader.Read(Rpu(PROFILE8_RPU)));
}

TEST(TestDolbyVisionRpu, AnRpuWithAResidualQuantisedAsTheIdentityHasAMel)
{
  CRpuReader reader;
  EXPECT_EQ(EnhancementLayer::MEL, reader.Read(Rpu(MEL_RPU)));
}

TEST(TestDolbyVisionRpu, AnRpuWithAResidualOfItsOwnHasAFel)
{
  CRpuReader reader;
  EXPECT_EQ(EnhancementLayer::FEL, reader.Read(Rpu(FEL_RPU)));
}

TEST(TestDolbyVisionRpu, AnRpuReferringBackHasTheLayerOfTheMappingItRefersTo)
{
  CRpuReader reader;
  ASSERT_EQ(EnhancementLayer::FEL, reader.Read(Rpu(FEL_RPU)));
  EXPECT_EQ(EnhancementLayer::FEL, reader.Read(MAPPING_0_RPU));
  ASSERT_EQ(EnhancementLayer::MEL, reader.Read(Rpu(MEL_RPU)));
  EXPECT_EQ(EnhancementLayer::MEL, reader.Read(MAPPING_0_RPU));

  // FFmpeg rejects an RPU referring to a mapping it hasn't read
  EXPECT_FALSE(CRpuReader().Read(MAPPING_0_RPU));
}

TEST(TestDolbyVisionRpu, AnRpuFFmpegRejectsIsNotRead)
{
  const std::vector<uint8_t> rpu{Rpu(FEL_RPU)};

  // Cut short
  EXPECT_FALSE(CRpuReader().Read(std::span(rpu).first(rpu.size() / 2)));

  // Without the 0x80 terminator after its CRC
  std::vector<uint8_t> unterminated{rpu};
  unterminated.back() = 0x81;
  EXPECT_FALSE(CRpuReader().Read(unterminated));

  // Of a type other than 2
  std::vector<uint8_t> otherType{rpu};
  otherType[1] ^= 0x04;
  EXPECT_FALSE(CRpuReader().Read(WithCrc(otherType)));
}

TEST(TestDolbyVisionRpu, AnRpuWhoseCrcDoesntMatchIsNotRead)
{
  // Kodi's decoder doesn't have FFmpeg check the CRC, so such an RPU is left to it
  std::vector<uint8_t> rpu{Rpu(FEL_RPU)};
  ASSERT_EQ(rpu, WithCrc(rpu));
  rpu[rpu.size() - 2] ^= 0x01;
  EXPECT_FALSE(CRpuReader().Read(rpu));
}
